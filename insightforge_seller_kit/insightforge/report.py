def _df_to_html(df: pd.DataFrame, empty_message: str) -> str:
    if df is None or df.empty:
        return f"<p>{empty_message}</p>"
    display = df.copy()
    for col in display.select_dtypes(include=["float", "float64", "float32"]).columns:
        display[col] = display[col].map(lambda x: f"{x:.4g}" if pd.notna(x) else "")
    return display.to_html(index=False, escape=True, classes="data-table")


def render_html_report(analysis: dict[str, Any], title: str = "InsightForge Technical Data Report") -> str:
    template = Template(HTML_TEMPLATE)
    return template.render(
        title=title,
        generated_at=datetime.now().strftime("%Y-%m-%d %H:%M"),
        rows=analysis["shape"]["rows"],
        columns=analysis["shape"]["columns"],
        numeric_count=len(analysis["types"]["numeric"]),
        anomaly_count=analysis["anomaly_count"],
        recommendations=analysis["recommendations"],
        checks=analysis["quality_checks"],
        numeric_summary_html=_df_to_html(analysis["numeric_summary"], "No numeric columns found."),
        correlations_html=_df_to_html(analysis["correlations"], "Not enough numeric columns for correlation analysis."),
        anomalies_html=_df_to_html(analysis["anomalies"], "No anomaly candidates detected or dataset too small."),
    )


def save_html_report(analysis: dict[str, Any], output_path: str | Path, title: str = "InsightForge Technical Data Report") -> Path:
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_html_report(analysis, title), encoding="utf-8")
    return path
